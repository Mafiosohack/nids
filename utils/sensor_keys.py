"""Per-sensor identity: one key per sensor, and a fixed list of what each may say.

## Why not one shared key

The old design had one pre-shared key, published in this repository as a
default, and three sensors that hardcoded it. Whoever knew it could claim
anything: any severity, any rule, any source IP, and - through a forged
"SSH Login" - that a shell between two hosts was a legitimate session, which
silenced shell detection for that pair.

Each sensor now has its own key and a SCOPE: the alert types it exists to
report. A stolen ML-sensor key can make noisy ML alerts. It cannot vouch for a
login and cannot claim a packet rule like "Breach". That is least privilege
applied to machines, which is all role-based access control is.

## Why it needs no configuration

`main.py` creates `sensor_keys.json` (owner-only permissions) on first start.
A sensor on the same machine reads its key from that file by name. A sensor on
another machine sets one variable, NIDS_SENSOR_KEY, to the value printed by:

    python -m utils.sensor_keys show ml        # or host / cloud

The file is gitignored. Delete it and restart to rotate every key.
"""

import json
import os
import secrets
import sys
from pathlib import Path
from typing import Dict, Optional

# Alert types each bundled sensor actually sends. Adding a sensor, or a new
# alert type to one, is a deliberate edit here - not something a key-holder
# can extend by posting a new string.
SENSOR_SCOPES: Dict[str, frozenset] = {
    "ml": frozenset({"ML Anomaly"}),
    "host": frozenset({"Host Brute Force", "SSH Login", "Root Access",
                       "Sensitive File Access", "Persistence"}),
    "cloud": frozenset({"Cloud Port Scan", "Cloud Recon", "Cloud Brute Force",
                        "Cloud UDP Amplification", "Data Exfiltration",
                        "Lateral Movement", "Impossible Travel"}),
}

# Sensors whose "SSH Login" is trusted to vouch for an interactive session.
# Only the host sensor reads auth.log; nothing else has the evidence.
SESSION_AUTHORITIES = frozenset({"host"})

# The key this repository used to publish. Never accepted, even if configured.
PUBLIC_DEFAULT_KEY = "sensor-key-change-me-in-production"

DEFAULT_PATH = os.environ.get("NIDS_SENSOR_KEYS", "sensor_keys.json")
ENV_KEY = "NIDS_SENSOR_KEY"


class SensorKeyError(RuntimeError):
    """A sensor could not find its key. The message says how to fix it."""


def _write_private(path: Path, data: dict) -> None:
    """Atomic write, created owner-read/write only (0600) on POSIX."""
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(str(tmp), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)
    os.replace(tmp, path)
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def load_or_create(path=DEFAULT_PATH) -> Dict[str, str]:
    """Return {sensor_name: key}, generating any key that does not exist yet."""
    p = Path(path)
    data = {"sensors": {}}
    if p.exists():
        with open(p, encoding="utf-8") as fh:
            data = json.load(fh) or {"sensors": {}}
    keys = dict(data.get("sensors") or {})
    missing = [n for n in SENSOR_SCOPES if not keys.get(n)]
    for name in missing:
        keys[name] = secrets.token_urlsafe(32)
    if missing:
        _write_private(p, {"_comment": "Generated by main.py. Owner-only. "
                                       "Delete to rotate every sensor key.",
                           "sensors": keys})
    return {n: keys[n] for n in SENSOR_SCOPES}


def identify(presented: str, keys: Dict[str, str]) -> Optional[str]:
    """Which sensor holds this key, or None. Constant-time per comparison, and
    every key is compared so the time does not depend on which one matched."""
    import hmac
    found = None
    p = (presented or "").encode()
    for name, key in keys.items():
        if hmac.compare_digest(p, (key or "").encode()):
            found = name
    return found


def key_for(sensor: str, path=DEFAULT_PATH) -> str:
    """The key a sensor should send: NIDS_SENSOR_KEY if set, else its entry in
    the local key file."""
    env = os.environ.get(ENV_KEY, "").strip()
    if env:
        return env
    p = Path(path)
    try:
        with open(p, encoding="utf-8") as fh:
            key = ((json.load(fh) or {}).get("sensors") or {}).get(sensor)
    except FileNotFoundError:
        key = None
    except (OSError, ValueError) as e:
        raise SensorKeyError(
            f"Cannot read {p}: {e}. Run this sensor as the same user as main.py, "
            f"or set {ENV_KEY}.") from e
    if not key:
        raise SensorKeyError(
            f"No key for sensor '{sensor}'. Start main.py once on this machine "
            f"(it creates {p.name}), or on a remote sensor set {ENV_KEY} to the "
            f"value of:  python -m utils.sensor_keys show {sensor}")
    return key


def _main(argv) -> int:
    if len(argv) >= 2 and argv[0] == "show" and argv[1] in SENSOR_SCOPES:
        print(load_or_create()[argv[1]])
        return 0
    if argv[:1] == ["list"]:
        for name, scope in SENSOR_SCOPES.items():
            print(f"{name:6s} may report: {', '.join(sorted(scope))}")
        return 0
    print("usage: python -m utils.sensor_keys show {ml|host|cloud} | list")
    return 2


if __name__ == "__main__":
    sys.exit(_main(sys.argv[1:]))
